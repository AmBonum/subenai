// Pure SQL builder for E66.3 real-case templates. Shared by
// scripts/generate-template-seeds.ts (writes the migration) and the Vitest
// drift check (regenerates in memory and compares to the committed file).
import { createHash } from "node:crypto";

import { REAL_CASE_TEMPLATES, type RealCaseTemplate } from "../src/content/templates/real-cases";
import { E37_DB_UUID_TO_BANK_ID } from "../src/lib/quiz/bank/db-ids";

const URL_NAMESPACE = "6ba7b811-9dad-11d1-80b4-00c04fd430c8";

export function uuidv5(name: string, namespace: string = URL_NAMESPACE): string {
  const ns = Buffer.from(namespace.replace(/-/g, ""), "hex");
  const hash = createHash("sha1").update(ns).update(name, "utf8").digest().subarray(0, 16);
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const hex = hash.toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const E37_BANK_ID_TO_DB_UUID = new Map(
  [...E37_DB_UUID_TO_BANK_ID].map(([uuid, bankId]) => [bankId, uuid]),
);

// E37 questions were seeded under UUIDs whose source slugs were never
// recorded, so they resolve through the pinned map instead of the hash.
export function questionDbUuid(bankSlug: string): string {
  return E37_BANK_ID_TO_DB_UUID.get(bankSlug) ?? uuidv5(bankSlug);
}

export function templateDbId(template: RealCaseTemplate): string {
  return template.legacyId ?? uuidv5(`template:${template.slug}`);
}

const lit = (value: string) => `'${value.replace(/'/g, "''")}'`;

// Ids missing from public.questions are dropped at apply time (order kept),
// so a template never points at a question the respondent RPC cannot load.
function questionIdsExpr(template: RealCaseTemplate): string {
  const ids = template.questionSlugs.map((s) => `    ${lit(questionDbUuid(s))}`).join(",\n");
  return `ARRAY(
  SELECT u.id FROM unnest(ARRAY[
${ids}
  ]::uuid[]) WITH ORDINALITY AS u(id, ord)
  WHERE EXISTS (SELECT 1 FROM public.questions q WHERE q.id = u.id)
  ORDER BY u.ord
)`;
}

function updateLegacy(t: RealCaseTemplate): string {
  return `-- ${t.slug}
UPDATE public.templates SET
  description = ${lit(t.description)},
  question_ids = ${questionIdsExpr(t)},
  gdpr_purpose = ${lit(t.gdprPurpose)},
  age_rating = ${lit(t.ageRating)},
  author_display_name = 'subenai'
WHERE slug = ${lit(t.slug)} AND owner_id IS NULL;`;
}

function upsertNew(t: RealCaseTemplate): string {
  return `-- ${t.slug}
INSERT INTO public.templates (
  id, title, description, question_ids, gdpr_purpose, visibility, status,
  license, author_display_name, age_rating, slug, published_at
) VALUES (
  ${lit(templateDbId(t))},
  ${lit(t.title)},
  ${lit(t.description)},
  ${questionIdsExpr(t)},
  ${lit(t.gdprPurpose)}, 'public', 'published',
  'cc-by-4.0', 'subenai', ${lit(t.ageRating)}, ${lit(t.slug)}, now()
)
ON CONFLICT (id) DO UPDATE SET
  title = EXCLUDED.title,
  description = EXCLUDED.description,
  question_ids = EXCLUDED.question_ids,
  gdpr_purpose = EXCLUDED.gdpr_purpose,
  visibility = EXCLUDED.visibility,
  status = EXCLUDED.status,
  author_display_name = EXCLUDED.author_display_name,
  age_rating = EXCLUDED.age_rating,
  slug = EXCLUDED.slug;`;
}

export function buildTemplateSeedsSql(
  templates: readonly RealCaseTemplate[] = REAL_CASE_TEMPLATES,
): string {
  const legacy = templates.filter((t) => t.legacyId);
  const fresh = templates.filter((t) => !t.legacyId);
  return `-- ============================================================================
-- E66.3 — real-case templates for /sablony (${legacy.length} filled + ${fresh.length} new)
-- GENERATED by scripts/generate-template-seeds.ts from
-- src/content/templates/real-cases.ts — do not edit by hand.
-- ============================================================================
-- Idempotent: legacy rows are updated by slug, new rows upsert on their
-- deterministic id (UUIDv5 of 'template:<slug>'). question_ids are UUIDv5 ids
-- of bank slugs already seeded into public.questions; ids absent from the
-- table are skipped. The default-template guard trigger is disabled for the
-- duration of the transaction because the SQL editor runs without an admin
-- JWT; it is re-enabled before COMMIT.
-- ============================================================================

BEGIN;

ALTER TABLE public.templates DISABLE TRIGGER templates_forbid_default_mutation;

${legacy.map(updateLegacy).join("\n\n")}

${fresh.map(upsertNew).join("\n\n")}

ALTER TABLE public.templates ENABLE TRIGGER templates_forbid_default_mutation;

COMMIT;

-- Self-check after applying:
--   SELECT slug, cardinality(question_ids) FROM public.templates
--    WHERE owner_id IS NULL ORDER BY slug; -- expect ${templates.length} rows, none with 0
`;
}
