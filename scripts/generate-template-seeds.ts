#!/usr/bin/env tsx
// E66.3 — emit the idempotent real-case templates migration and mirror it
// into DEPLOY_SETUP.sql. Deterministic: unchanged content → byte-identical
// output. Per CLAUDE.md the owner applies the SQL to prod after merge.
//
//   npm run templates:seeds
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { buildTemplateSeedsSql } from "./template-seeds-sql";

const MIGRATION_FILE = "supabase/migrations/20261012120000_e66_real_case_templates.sql";
const DEPLOY_BEGIN = "-- >>> E66.3 real-case templates (generated by npm run templates:seeds)";
const DEPLOY_END = "-- <<< E66.3 real-case templates";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sql = buildTemplateSeedsSql();

writeFileSync(join(root, MIGRATION_FILE), sql);

const deployPath = join(root, "DEPLOY_SETUP.sql");
const deploy = readFileSync(deployPath, "utf8");
const section = `${DEPLOY_BEGIN}\n${sql}${DEPLOY_END}\n`;
const start = deploy.indexOf(DEPLOY_BEGIN);
const next =
  start === -1
    ? `${deploy.trimEnd()}\n\n${section}`
    : `${deploy.slice(0, start)}${section}${deploy.slice(deploy.indexOf(DEPLOY_END, start) + DEPLOY_END.length + 1)}`;
writeFileSync(deployPath, next);

console.log(`Wrote ${MIGRATION_FILE} and synced DEPLOY_SETUP.sql`);
